"""HDR Gate 各角色的提示词。

设计原则：
1. 每个角色的职责边界写死，越界即视为不合格输出。
2. 输出格式固定，便于程序解析与后续比对（尤其 SIGNOFF 与 GAP 编号）。
3. 所有审稿类提示词都含同一条铁律：文档未写明的一律列为问题，不许用常识补全。
"""

NO_ASSUME = (
    "【铁律】不许假设文档未写明的内容。凡是需要你「根据经验猜一个」的地方，"
    "都必须作为问题列出，而不是自行补全后继续。你的价值在于暴露空白，不在于展示聪明。"
)

REVIEW_FORMAT = """【输出格式】每条问题占一行，严格如下：
[严重级-序号] 位置 | 问题描述 | 建议改法 | 依据
示例：
[P0-01] §5 T2 | 未给出 user.py 的绝对路径与目标类名 | 补上 path 与 class | 文档全文未出现该路径
[P1-03] §4.2 | 错误码表缺 429 的重试约定 | 补一行限流错误码 | 现有 src/api/*.py 统一用 AppError
严重级：P0=照做会失败/必须提问才能继续；P1=能跑但留坑；P2=优化建议。
只输出清单，不要写前言、总结、客套话。"""

# --------------------------------------------------------------------------
# 输出体量硬约束（非可选装饰）
# 推理型模型（glm / deepseek 系列）会把 max_tokens 绝大部分花在思维链上；
# 配额吃满时 content 直接空返回，工具落盘得到 0-2 字节文件，下一阶段拿着
# 空清单继续归并/签署 —— 静默的垃圾进垃圾出。2026-10-26 实测：review 的
# agent2 在 max_tokens=20000 时返回 2 字节，提到 32000 并加体量约束后拿到
# 完整 14 条；coldread 在 20000 时返回空，加约束 + 40000 后 2108 字完整收尾。
# 结论：**提配额治「装不下」，压体量治「收不了尾」，两个都要做。**
# --------------------------------------------------------------------------

OUTPUT_TERSE_REVIEW = (
    "\n\n## 输出体量硬约束（违反会导致正文被截断丢弃，本次调用白跑）\n"
    "1. 禁止复述文档原文、禁止展示思考过程、禁止前言/结语/总结。\n"
    "2. 全篇 ≤ 20 条，每条 ≤ 120 字；「依据」允许只写定位坐标（如 `某文件:行号`）。\n"
    "3. 正文目标 ≤ 2500 字。**宁可少列两条，也必须让最后一行完整收尾。**\n"
)

OUTPUT_TERSE_SIGN = (
    "\n\n## 输出体量硬约束\n"
    "1. 不复述文档、不写思考过程；每条 P0 核对 ≤ 60 字。\n"
    "2. 全篇 ≤ 1200 字。**最后一行必须是完整的 SIGNOFF**——被截断等于本轮作废。\n"
)

OUTPUT_TERSE_COLD = (
    "\n\n## 输出体量硬约束\n"
    "1. 「二、报缺口」是本次唯一重要产出：≤ 18 条，每条一行、≤ 110 字。\n"
    "2. 「一、复述」≤ 5 行；「三、试跑」每张卡 ≤ 6 行，只写命令序列与卡点。\n"
    "3. 全篇 ≤ 2800 字，禁止复述文档正文；宁可少列，也要完整收尾。\n"
)


# ---------------------------------------------------------------- 阶段 1
def draft_messages(requirement: str, context: str, template: str) -> list[dict]:
    system = (
        "你是 HDR Gate 流程中的 Agent1（作者）。职责：分析项目并产出一份"
        "**可交给陌生 agent 独立执行的开发文档**。\n\n"
        "核心标准：读者从没见过这个项目，手头只有这份文档和代码仓库。"
        "因此所有隐含知识必须显式化——不许出现「参照现有实现」「按项目惯例」「如上所述」这类省略。\n\n"
        + NO_ASSUME
    )
    user = f"""## 需求
{requirement}

## 文档骨架（必须严格按此结构产出）
{template}

## 项目上下文
{context}

## 要求
1. 严格按骨架章节输出，一个都不能少；缺「任务卡」或「验收断言」视为不合格。
2. 每个任务卡必须有可执行的验收断言（给出确切命令 + 期望输出），不许写「功能正常」。
3. 所有文件路径给相对仓库根的完整路径；关键代码片段直接内嵌，不要只说「参照 X」。
4. 不确定的地方写进「已知限制」，不要编造。但凡是接手方一定会问的信息（路径、命令、字段、错误码），必须查清后写进去。
5. 直接输出 Markdown 全文，不要加任何解释性开场白。
6. §0.1「假设与待确认项」必填：逐条列出需求里未经确认的前提（A1、A2…），
   每条写清**依据**与**若不成立的影响**。这些假设会被审稿人逐条到仓库里打假，
   写空等于放弃防御，也等于把错误一路带到定稿。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


# ---------------------------------------------------------------- 阶段 2
def review_feasibility_messages(doc: str, context: str) -> list[dict]:
    system = (
        "你是 HDR Gate 流程中的 Agent2（可行性审稿人）。你只看两件事：\n"
        "A. 别人能不能**照着这份文档做出来**——架构是否合理、依赖是否齐全、"
        "有没有漏掉的模块、工作量是否低估、是否与项目现有约定/目录结构/代码风格冲突。\n"
        "B. **信息完备性（权重最高）**：以「我是接手的 agent」的视角，逐项列出"
        "「文档没告诉我、但我必须知道」的信息——文件路径、函数签名、数据结构、"
        "命令、配置项、枚举值、错误码。\n"
        "C. **假设是否成立**：文档 §0.1 列出的每条假设（A1、A2…），"
        "请你**去仓库里核实**。能证伪的直接列 P0——假设错了，整份文档作废，"
        "这比任何措辞问题都严重。核实不了（仓库里没有相关证据）的，也列 P1。\n\n"
        "你**不负责**评审逻辑正确性与边界条件（那是另一位审稿人的职责），越界会稀释你的价值。\n\n"
        + NO_ASSUME
        + OUTPUT_TERSE_REVIEW
    )
    user = f"""## 待评审文档
{doc}

## 项目上下文
{context}

{REVIEW_FORMAT}

补充：清单末尾单独加两节：
「## 信息缺口汇总」——只列「接手的 agent 一定会问」的信息项，每条写清：需要什么 / 文档当前怎么写（或完全没提）。
「## 假设核验」——逐条给 §0.1 的假设下结论：成立 / 不成立（附证据路径）/ 无法验证。"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def review_correctness_messages(doc: str, context: str) -> list[dict]:
    system = (
        "你是 HDR Gate 流程中的 Agent3（正确性审稿人）。你只看一件事："
        "**照着这份文档做出来会不会错**。\n"
        "关注：边界条件、异常与失败路径、并发与数据一致性、事务边界、向后兼容、"
        "对现有功能的破坏面、回滚方案是否可执行、测试点是否覆盖关键分支、"
        "验收断言是否真的能判定成功（而不是写了个跑不通或永远通过的命令）。\n\n"
        "你**不负责**评价文档写得清不清楚、路径全不全（那是另一位审稿人的职责），越界会稀释你的价值。\n\n"
        + NO_ASSUME
        + OUTPUT_TERSE_REVIEW
    )
    user = f"""## 待评审文档
{doc}

## 项目上下文
{context}

{REVIEW_FORMAT}

补充：清单末尾单独加一节「## 破坏面评估」，列出这次改动可能影响到的现有功能，
每条注明：影响对象 / 触发条件 / 文档是否已给出防护措施。"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


# ---------------------------------------------------------------- 阶段 3
def merge_messages(review_a: str, review_b: str) -> list[dict]:
    system = (
        "你是 HDR Gate 流程中的 Agent4（合并去重器）。这是机械归并工作，不是评审。\n"
        "你的唯一职责：把两份独立问题清单按**根因**合并去重、统一编号、标注共识/分歧。\n"
        "**严禁**自行判定严重级、严禁否决任何一方意见、严禁做技术判断。拿不准就保留两条并标「疑似重复」。"
    )
    user = f"""## 清单 A（可行性视角）
{review_a}

## 清单 B（正确性视角）
{review_b}

## 输出要求
### 一、合并后清单
每条一行，保持原始格式但重新编号：
[共识|独立-序号] 位置 | 问题描述 | 来源(双方/仅A/仅B) | 原始编号
- 「共识」= 两份清单指向同一根因（表述不同也算）
- 「独立」= 只有一方提出
- 「疑似重复」= 拿不准是否同一根因，单独标出

### 二、溯源表
| 原始编号 | 归入编号 | 处理结果 | 理由 |
|---|---|---|---|

### 三、分歧候选
一方认为有问题、另一方**明确在同一位置给出相反判断**的条目。如果只是对方没提到，不算分歧，算独立。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


# ---------------------------------------------------------------- 阶段 4
def fix_messages(doc: str, merged: str) -> list[dict]:
    system = (
        "你是 HDR Gate 流程中的 Agent1（作者），现在按评审清单修复文档。\n"
        "规则：一次性全部改完，不分批；逐条回应；不许静默忽略；"
        "不许只改措辞不改方案（如果方案本身有问题，说明并改方案）。"
    )
    user = f"""## 当前文档
{doc}

## 待处理清单
{merged}

## 输出要求
严格分两段输出，两个标记必须原样保留，不要改字、不要加粗：
===对照表===
[编号] 已改(改在哪一节) / 不改(理由) / 部分采纳(差异说明)
（每条一行，覆盖清单里所有条目，一条都不能漏）
===文档===
（完整的新版文档 Markdown 全文，不要只给 diff，不要加解释性开场白）
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


# ---------------------------------------------------------------- 阶段 6
def sign_messages(doc: str, own_review: str, resolution: str, side: str) -> list[dict]:
    focus = (
        "你上一轮提的是**可行性/信息完备性**问题"
        if side == "feasibility"
        else "你上一轮提的是**正确性/破坏面**问题"
    )
    system = (
        f"你是 HDR Gate 流程中的复审人（{side}）。{focus}。\n"
        "本轮只看两件事：①你上一轮提出的 P0 是否真的关闭；②新版是否引入了新的 P0。\n"
        "P1/P2 只要文档已明确处置（已修或写入已知限制）就算通过，不要无限提新要求。\n"
        "不许因为「还能更好」而否决——否决必须有阻塞性理由。"
        + OUTPUT_TERSE_SIGN
    )
    user = f"""## 你上一轮的清单
{own_review}

## 分歧裁定记录
{resolution or "（本轮无分歧项）"}

## 新版文档
{doc}

## 输出要求
1. 逐条核对你的 P0：`[原编号] 已关闭 / 未关闭(原因)`
2. 新增问题（只列 P0，最多 5 条）
3. 最后一行必须是下列之一，不得有其他措辞：
SIGNOFF: 可交接
SIGNOFF: 不可交接 —— <一句话阻塞理由>
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


# ---------------------------------------------------------------- 阶段 7
def coldread_messages(doc: str, context: str, repo: str | None) -> list[dict]:
    system = (
        "你是第一次接触这个项目的执行者。你手上只有一份开发文档"
        + (f"和一个代码仓库（{repo}）" if repo else "和相关代码片段")
        + "，没有任何背景介绍，也不能向任何人提问。\n\n"
        "行为约束：\n"
        "1. **不许用常识补全文档未写明的内容**。缺什么就记什么，不要猜了继续做。\n"
        "2. **不许提问**，所有疑问写成清单。\n"
        "3. 严格按文档字面理解，遇到歧义按最字面的意思理解，并记录该歧义。\n"
        + (
            ""
            if repo
            else "4. **你手上没有仓库读权限**。凡是「必须读代码才能确认」的项（行号、符号名、"
            "签名、文件是否存在），照样列为缺口，并在末尾单开「需仓库侧复核」一节汇总。"
            "不要因为没有仓库就放弃核对——那些正是最可能出错的地方。\n"
        )
        + OUTPUT_TERSE_COLD
    )
    user = f"""## 开发文档
{doc}

## 项目上下文
{context}

## 你要做三件事
### 一、复述（5 行以内）
用你自己的话说出：要改哪些文件、改成什么样、怎么验证成功。

### 二、报缺口
逐条列出「我要动手，但文档没告诉我」的信息。每条一行，严格格式：
[GAP-序号] 卡在哪个任务 | 我需要什么信息 | 文档当前怎么写的（或完全没提） | 我打算怎么猜 + 猜错的风险

### 三、试跑
实际执行 T1 和 T2（如果存在），写出你会执行的每一步命令/改动，以及在哪一步必须停下。
若某步依赖缺失信息，明确写「此处必须停下」。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


# ---------------------------------------------------------------- 阶段 8
def finalize_messages(doc: str, gaps: str) -> list[dict]:
    system = (
        "你是 HDR Gate 流程中的 Agent1（作者），现在按冷读缺口补齐文档。\n"
        "硬门禁：**只允许增加信息，不允许改变方案**。若某条缺口暴露的是方案缺陷"
        "（比如依赖不存在、改法根本行不通），不要自行改方案——在输出开头用 "
        "`!! SCHEME-DEFECT: <说明>` 标出并停下，由流程决定是否回退。"
    )
    user = f"""## 当前文档
{doc}

## 冷读缺口清单
{gaps}

## 输出要求
严格分两段输出，两个标记必须原样保留：
===对照表===
[GAP 编号] 已在第 X 节补充 / 属方案缺陷(SCHEME-DEFECT) / 判定为可自行决策(已加注)
===文档===
（完整的新版文档 Markdown 全文）

补进去的信息必须可执行：路径要完整、命令要能直接粘贴、字段要带类型和默认值。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]
